// CYP-423 — generate the maritime `--md-sys-color-*` CSS layer from the single token source
// (src/ui/maritimeTokens.data.mjs). "Generate, don't commit" (like contract:gen): the output is gitignored and
// rebuilt by `npm run tokens:gen` (chained into `build`). Emitting all four theme blocks from ONE source keeps the
// light/dark values in sync (no hand-repetition drift). Theme-aware per the house rule: light is the base, dark via
// prefers-color-scheme, and an explicit [data-theme] wins in BOTH directions.
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import { MARITIME_TOKENS, EVENT_SEVERITY } from '../src/ui/maritimeTokens.data.mjs'
import { PO_ACCENT_RAW, WORKER_ACCENTS_RAW } from '../src/ui/senderAccents.data.mjs'
import { readableAccentOn } from '../src/ui/colorAdapt.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const OUT = resolve(here, '../src/ui/tokens.generated.css')

const kebab = (role) => `--md-sys-color-${role.replace(/([A-Z])/g, '-$1').toLowerCase()}`
const decls = (scheme, indent) =>
  Object.entries(scheme)
    .map(([role, hex]) => `${indent}${kebab(role)}: ${hex};`)
    .join('\n')

const { light, dark } = MARITIME_TOKENS

// CYP-436: the sender-identity accents, ADAPTED to clear the 4.5:1 text floor on each theme's surface (the CYP-14
// pastels wash out on the white light surface → darkened; on navy they already clear → unchanged). Names stay
// colored (UIUX intent) and readable in both themes; the a11y guard measures the same readableAccentOn values.
const senderDecls = (surface, indent) => {
  const lines = [`${indent}--sender-accent-po: ${readableAccentOn(PO_ACCENT_RAW, surface)};`]
  WORKER_ACCENTS_RAW.forEach((raw, i) => lines.push(`${indent}--sender-accent-${i}: ${readableAccentOn(raw, surface)};`))
  return lines.join('\n')
}

// CYP-468 (F2): the event-log severity palette, emitted as `--event-sev-*` from the same token source (previously
// hand-hardcoded in index.css, outside this gen guard). One definition per theme → no drift.
const eventSevDecls = (scheme, indent) =>
  Object.entries(scheme)
    .map(([key, hex]) => `${indent}--event-sev-${key}: ${hex};`)
    .join('\n')

const css = `/* GENERATED by scripts/generate-tokens-css.mjs from src/ui/maritimeTokens.data.mjs — DO NOT EDIT.
   CYP-423 maritime M3 token layer. Regenerate with \`npm run tokens:gen\`. */

/* Light is the base scheme. */
:root {
${decls(light, '  ')}
${senderDecls(light.surface, '  ')}
${eventSevDecls(EVENT_SEVERITY.light, '  ')}
}

/* Dark follows the OS preference, unless an explicit light theme is forced. */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${decls(dark, '    ')}
${senderDecls(dark.surface, '    ')}
${eventSevDecls(EVENT_SEVERITY.dark, '    ')}
  }
}

/* An explicit theme toggle wins in both directions (stamps data-theme on :root). */
:root[data-theme='dark'] {
${decls(dark, '  ')}
${senderDecls(dark.surface, '  ')}
${eventSevDecls(EVENT_SEVERITY.dark, '  ')}
}
:root[data-theme='light'] {
${decls(light, '  ')}
${senderDecls(light.surface, '  ')}
${eventSevDecls(EVENT_SEVERITY.light, '  ')}
}
`

writeFileSync(OUT, css)
console.log(
  `[CYP-423/436] wrote ${OUT} (${Object.keys(light).length} M3 roles + ${WORKER_ACCENTS_RAW.length + 1} sender accents, × light/dark)`,
)
